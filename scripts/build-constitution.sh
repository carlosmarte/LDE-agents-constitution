#!/usr/bin/env bash
# Build CONSTITUTION.md from every articles/<X>-<name>/ARTICLE.md, A to Z.
#
# Usage: build-constitution.sh [--check]
#   With no argument, writes CONSTITUTION.md if it is out of date.
#   With --check, changes nothing. Exits 0 if the file is current, 1 if not.

set -euo pipefail
export LC_ALL=C

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
target="$root/CONSTITUTION.md"

case "${1:-}" in
  ""|--check) ;;
  *) echo "usage: build-constitution.sh [--check]" >&2; exit 2 ;;
esac

cd "$root"

# A folder being scaffolded has no ARTICLE.md yet; AGENTS.md section 6 catches one left that way.
articles=()
for dir in articles/[A-Z]-*; do
  if [ -f "$dir/ARTICLE.md" ]; then
    articles+=("$dir")
  elif [ -d "$dir" ]; then
    echo "warning: $dir has no ARTICLE.md; skipped" >&2
  fi
done
[ "${#articles[@]}" -gt 0 ] || { echo "error: no articles found under articles/" >&2; exit 2; }

# Lower every heading one level and make relative links resolve from the repository root.
render_article() {
  awk -v dir="$1" '
    function resolve(link, path) {
      if (link ~ /^[A-Za-z][A-Za-z0-9+.-]*:/ || link ~ /^[#\/]/) return link
      path = dir "/" link
      while (sub(/\/\.\//, "/", path)) {}
      while (sub(/[^\/]+\/\.\.\//, "", path)) {}
      return path
    }
    function rewrite(rest, out) {
      out = ""
      while (match(rest, /\]\([^)]+\)/)) {
        out = out substr(rest, 1, RSTART + 1) resolve(substr(rest, RSTART + 2, RLENGTH - 3)) ")"
        rest = substr(rest, RSTART + RLENGTH)
      }
      return out rest
    }
    /^(```|~~~)/ { fence = !fence; print; next }
    fence { print; next }
    /^#+ / { $0 = "#" $0 }
    { print rewrite($0) }
  ' "$1/ARTICLE.md"
}

# GitHub heading anchor: lowercase, punctuation dropped, spaces become hyphens.
anchor() {
  printf '%s' "$1" | tr '[:upper:]' '[:lower:]' | sed -e 's/[^a-z0-9 -]//g' -e 's/ /-/g'
}

render() {
  echo '<!-- Generated by scripts/build-constitution.sh. Do not edit; change articles/<X>-<name>/ARTICLE.md and rebuild. -->'
  echo
  echo '# Constitution'
  echo
  echo 'Every article of the LDE agents constitution, A to Z. Each article'"'"'s definitions, laws, procedures, and amendments are in its folder under [articles/](articles/).'
  echo
  for dir in "${articles[@]}"; do
    title="$(sed -n 's/^# //p' "$dir/ARTICLE.md" | head -n 1)"
    echo "- [$title](#$(anchor "$title"))"
  done
  for dir in "${articles[@]}"; do
    echo
    echo '---'
    echo
    render_article "$dir"
  done
}

tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT
render > "$tmp"

if [ -f "$target" ] && cmp -s "$tmp" "$target"; then
  exit 0
fi

if [ "${1:-}" = "--check" ]; then
  echo "CONSTITUTION.md is out of date; run scripts/build-constitution.sh" >&2
  exit 1
fi

cat "$tmp" > "$target"
echo "Updated CONSTITUTION.md"
